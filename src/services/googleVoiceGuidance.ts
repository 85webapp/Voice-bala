// In-memory client audio cache + in-flight dedup map so prefetched / hovered items speak instantaneously (< 5ms)
const chunkAudioCache = new Map<string, ArrayBuffer>();
const inFlightChunkFetches = new Map<string, Promise<ArrayBuffer | null>>();
const MAX_CLIENT_AUDIO_CACHE = 200;

function getChunkCacheKey(lang: VoiceLanguageCode, chunk: string): string {
  return `${lang}:${chunk}`;
}

function storeChunkInCache(key: string, buffer: ArrayBuffer) {
  if (chunkAudioCache.size >= MAX_CLIENT_AUDIO_CACHE) {
    const oldestKey = chunkAudioCache.keys().next().value;
    if (oldestKey) chunkAudioCache.delete(oldestKey);
  }
  chunkAudioCache.set(key, buffer);
}

function splitClientSpeechChunks(text: string, maxLength = 185): string[] {
  if (text.length <= maxLength) return [text];
  const sentences = text.split(/(?<=[।!?.\n])\s+/);
  const chunks: string[] = [];
  let cur = '';
  for (const s of sentences) {
    const trimmed = s.trim();
    if (!trimmed) continue;
    if ((cur + ' ' + trimmed).trim().length <= maxLength) {
      cur = cur ? `${cur} ${trimmed}` : trimmed;
    } else {
      if (cur.trim()) chunks.push(cur.trim());
      if (trimmed.length > maxLength) {
        const subParts = trimmed.split(/(?<=[,;])\s+/);
        let subCur = '';
        for (const p of subParts) {
          if ((subCur + ' ' + p).trim().length <= maxLength) {
            subCur = subCur ? `${subCur} ${p}` : p;
          } else {
            if (subCur.trim()) chunks.push(subCur.trim());
            subCur = p;
          }
        }
        cur = subCur;
      } else {
        cur = trimmed;
      }
    }
  }
  if (cur.trim()) chunks.push(cur.trim());
  return chunks.length > 0 ? chunks : [text];
}

function getResolvedVoicePayload(serviceKey: string): {
  canonicalKey: string;
  userLang: VoiceLanguageCode;
  textToSpeak: string;
  chunks: string[];
} | null {
  const canonicalKey = resolveServiceKey(serviceKey);
  if (!canonicalKey || typeof window === 'undefined') return null;

  const userLang = (localStorage.getItem('userAudioLanguage') || localStorage.getItem('ctc_audio_language_v2') || 'hi') as VoiceLanguageCode;
  const serviceData = allServiceVoiceTexts[canonicalKey];
  if (!serviceData) return null;

  const rawText = serviceData[userLang] || serviceData['hi'] || '';
  if (!rawText) return null;

  const textToSpeak = rawText
    .replace(/['"“”‘’]/g, '')
    .replace(/सबमिट/g, 'सब्मिट')
    .replace(/\s+/g, ' ')
    .trim();
  if (!textToSpeak) return null;

  return {
    canonicalKey,
    userLang,
    textToSpeak,
    chunks: splitClientSpeechChunks(textToSpeak, 185)
  };
}

function fetchSingleTtsChunk(chunkText: string, userLang: VoiceLanguageCode): Promise<ArrayBuffer | null> {
  const cacheKey = getChunkCacheKey(userLang, chunkText);
  const cached = chunkAudioCache.get(cacheKey);
  if (cached) {
    return Promise.resolve(cached);
  }
  if (ttsBackendStatus === 'unavailable') {
    return Promise.resolve(null);
  }
  const existing = inFlightChunkFetches.get(cacheKey);
  if (existing) {
    return existing;
  }

  const reqPromise = fetch('/api/tts-audio', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ tl: userLang, q: chunkText })
  })
    .then(async (res) => {
      const contentType = (res.headers.get('content-type') || '').toLowerCase();
      if (!res.ok || !contentType.includes('audio')) {
        if (res.status === 404 || res.status === 405) {
          ttsBackendStatus = 'unavailable';
        }
        return null;
      }
      ttsBackendStatus = 'available';
      const ab = await res.arrayBuffer();
      if (!ab || ab.byteLength === 0) return null;
      storeChunkInCache(cacheKey, ab);
      return ab;
    })
    .catch(() => null)
    .finally(() => {
      inFlightChunkFetches.delete(cacheKey);
    });

  inFlightChunkFetches.set(cacheKey, reqPromise);
  return reqPromise;
}

/**
 * Quietly pre-warms the opening sentence (or full script on hover/pointerdown) into memory
 * so clicking starts speaking instantaneously.
 */
export function prefetchServiceVoice(serviceKey: string, includeAllChunks = false): void {
  if (typeof window === 'undefined' || ttsBackendStatus === 'unavailable') return;
  const resolved = getResolvedVoicePayload(serviceKey);
  if (!resolved) return;

  const targets = includeAllChunks ? resolved.chunks : [resolved.chunks[0]];
  for (const chunk of targets) {
    const key = getChunkCacheKey(resolved.userLang, chunk);
    if (!chunkAudioCache.has(key) && !inFlightChunkFetches.has(key)) {
      void fetchSingleTtsChunk(chunk, resolved.userLang);
    }
  }
}

const queuedPrefetchKeys: string[] = [];
const queuedPrefetchSet = new Set<string>();
let activePrefetchWorkers = 0;

function runPrefetchQueue() {
  if (ttsBackendStatus === 'unavailable') {
    queuedPrefetchKeys.length = 0;
    queuedPrefetchSet.clear();
    return;
  }
  while (activePrefetchWorkers < 3 && queuedPrefetchKeys.length > 0) {
    const nextKey = queuedPrefetchKeys.shift()!;
    queuedPrefetchSet.delete(nextKey);
    const resolved = getResolvedVoicePayload(nextKey);
    if (!resolved) continue;
    const firstChunk = resolved.chunks[0];
    const cacheKey = getChunkCacheKey(resolved.userLang, firstChunk);
    if (chunkAudioCache.has(cacheKey)) continue;

    activePrefetchWorkers++;
    void fetchSingleTtsChunk(firstChunk, resolved.userLang).finally(() => {
      activePrefetchWorkers--;
      runPrefetchQueue();
    });
  }
}

export function prefetchBatchVoices(serviceKeys: string[]): void {
  if (typeof window === 'undefined' || ttsBackendStatus === 'unavailable') return;
  for (const key of serviceKeys) {
    if (!key || queuedPrefetchSet.has(key)) continue;
    const resolved = getResolvedVoicePayload(key);
    if (!resolved) continue;
    const cacheKey = getChunkCacheKey(resolved.userLang, resolved.chunks[0]);
    if (chunkAudioCache.has(cacheKey) || inFlightChunkFetches.has(cacheKey)) continue;
    queuedPrefetchSet.add(key);
    queuedPrefetchKeys.push(key);
  }
  runPrefetchQueue();
}

type MicPermissionState = 'unknown' | 'prompt' | 'granted' | 'denied' | 'unsupported';
let micPermissionStatus: MicPermissionState = 'unknown';
let pendingMicRequest: Promise<MicPermissionState> | null = null;
let initialMicPromptAttempted = false;
let globalUnlockBound = false;

/**
 * Queries and requests browser microphone permission cleanly.
 * Immediately stops audio input tracks so no active recording indicator lingers.
 */
export async function requestMicrophonePermission(forceRetryOnDenied = false): Promise<MicPermissionState> {
  if (typeof navigator === 'undefined' || !navigator.mediaDevices || typeof navigator.mediaDevices.getUserMedia !== 'function') {
    micPermissionStatus = 'unsupported';
    return micPermissionStatus;
  }

  // Check current permission status via Permissions API if supported
  try {
    if (navigator.permissions && typeof navigator.permissions.query === 'function') {
      const status = await navigator.permissions.query({ name: 'microphone' as PermissionName });
      micPermissionStatus = status.state as MicPermissionState;
      status.onchange = () => {
        micPermissionStatus = status.state as MicPermissionState;
      };
      if (status.state === 'granted') {
        return 'granted';
      }
      if (status.state === 'denied' && !forceRetryOnDenied) {
        return 'denied';
      }
    }
  } catch {
    // Some browsers (e.g., Safari) throw on permissions.query({ name: 'microphone' })
  }

  if (micPermissionStatus === 'granted') {
    return 'granted';
  }
  if (micPermissionStatus === 'denied' && !forceRetryOnDenied) {
    return 'denied';
  }

  if (pendingMicRequest) {
    return pendingMicRequest;
  }

  pendingMicRequest = (async () => {
    try {
      const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
      try {
        stream.getTracks().forEach((track) => track.stop());
      } catch {}
      micPermissionStatus = 'granted';
      return 'granted';
    } catch {
      micPermissionStatus = 'denied';
      return 'denied';
    } finally {
      pendingMicRequest = null;
    }
  })();

  return pendingMicRequest;
}

export function getMicrophonePermissionState(): MicPermissionState {
  return micPermissionStatus;
}

/**
 * Unlocks AudioContext (with 1-sample silent buffer) & persistent HTMLAudioElement synchronously inside a user gesture.
 * Required by Chrome Mobile, iOS Safari, and Desktop browsers before async TTS playback.
 */
export function unlockAudioForPlayback() {
  if (typeof window === 'undefined') return;

  // 1. Unlock Web Audio API Context + play 1-sample silent buffer synchronously
  try {
    const AudioCtx = window.AudioContext || (window as any).webkitAudioContext;
    if (AudioCtx) {
      if (!sharedAudioContext) {
        sharedAudioContext = new AudioCtx();
      }
      if (sharedAudioContext.state === 'suspended') {
        void sharedAudioContext.resume().catch(() => {});
      }
      if (!isWebAudioBufferPrimed) {
        isWebAudioBufferPrimed = true;
        const silentBuffer = sharedAudioContext.createBuffer(1, 1, 22050);
        const source = sharedAudioContext.createBufferSource();
        source.buffer = silentBuffer;
        source.connect(sharedAudioContext.destination);
        source.start(0);
      }
    }
  } catch {}

  // 2. Unlock persistent HTMLAudioElement synchronously using a tiny silent WAV backup
  try {
    if (!sharedAudioElement) {
      sharedAudioElement = new Audio();
      sharedAudioElement.preload = 'auto';
      (sharedAudioElement as any).playsInline = true;
    }
    if (!isAudioElementUnlocked) {
      sharedAudioElement.muted = true;
      sharedAudioElement.src = SILENT_WAV_DATA_URI;
      const p = sharedAudioElement.play();
      if (p && typeof p.then === 'function') {
        p.then(() => {
          if (sharedAudioElement) {
            if (sharedAudioElement.src === SILENT_WAV_DATA_URI) {
              sharedAudioElement.pause();
            }
            sharedAudioElement.muted = false;
          }
          isAudioElementUnlocked = true;
        }).catch(() => {
          if (sharedAudioElement) {
            sharedAudioElement.muted = false;
          }
        });
      } else {
        sharedAudioElement.muted = false;
        isAudioElementUnlocked = true;
      }
    }
  } catch {}
}

/**
 * Silently probes & warms up /api/tts-audio on app mount so Vercel serverless lambdas
 * respond fast on first click and unavailability is known ahead of clicks.
 */
function probeTtsBackend() {
  if (ttsProbeStarted || typeof window === 'undefined') return;
  ttsProbeStarted = true;
  fetch('/api/tts-audio', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ tl: 'hi', q: 'नमस्ते' })
  })
    .then((res) => {
      const ct = (res.headers.get('content-type') || '').toLowerCase();
      if (res.ok && ct.includes('audio')) {
        ttsBackendStatus = 'available';
      } else if (res.status === 404 || res.status === 405) {
        ttsBackendStatus = 'unavailable';
      }
    })
    .catch(() => {
      // Keep status 'unknown' on transient offline error so real click still attempts TTS
    });
}

/**
 * Called on initial app mount:
 * 1. Requests microphone permission cleanly upon visiting the site/domain.
 * 2. Binds first-gesture audio unlock across all browsers.
 * 3. Warms up /api/tts-audio backend endpoint.
 */
export function initVoiceAndMicPermissions() {
  if (typeof window === 'undefined') return;

  probeTtsBackend();

  if (!initialMicPromptAttempted) {
    initialMicPromptAttempted = true;
    void requestMicrophonePermission(false);
  }

  if (!globalUnlockBound) {
    globalUnlockBound = true;
    const handleFirstInteraction = () => {
      unlockAudioForPlayback();
      if (micPermissionStatus === 'unknown' || micPermissionStatus === 'prompt') {
        void requestMicrophonePermission(false);
      }
      window.removeEventListener('pointerdown', handleFirstInteraction, true);
      window.removeEventListener('touchstart', handleFirstInteraction, true);
      window.removeEventListener('click', handleFirstInteraction, true);
      window.removeEventListener('keydown', handleFirstInteraction, true);
    };
    window.addEventListener('pointerdown', handleFirstInteraction, { capture: true, passive: true });
    window.addEventListener('touchstart', handleFirstInteraction, { capture: true, passive: true });
    window.addEventListener('click', handleFirstInteraction, { capture: true, passive: true });
    window.addEventListener('keydown', handleFirstInteraction, { capture: true, passive: true });
  }
}

type VoiceListener = (isPlaying: boolean, serviceKey: string | null) => void;
const listeners = new Set<VoiceListener>();

function notifyListeners() {
  const isSpeaking = Boolean(
    currentPlayingServiceKey !== null ||
    currentAudioBufferSource !== null ||
    (typeof window !== 'undefined' && 'speechSynthesis' in window && window.speechSynthesis.speaking) ||
    (currentAudioPlayer && !currentAudioPlayer.paused && Boolean(currentAudioPlayer.src) && currentAudioPlayer.src !== SILENT_WAV_DATA_URI)
  );
  listeners.forEach((listener) => {
    try {
      listener(isSpeaking, isSpeaking ? currentPlayingServiceKey : null);
    } catch (e) {
      console.warn('Voice listener error:', e);
    }
  });
}

export function subscribeVoiceState(listener: VoiceListener): () => void {
  listeners.add(listener);
  const isSpeaking = Boolean(
    currentPlayingServiceKey !== null ||
    currentAudioBufferSource !== null ||
    (typeof window !== 'undefined' && 'speechSynthesis' in window && window.speechSynthesis.speaking) ||
    (currentAudioPlayer && !currentAudioPlayer.paused && Boolean(currentAudioPlayer.src) && currentAudioPlayer.src !== SILENT_WAV_DATA_URI)
  );
  listener(isSpeaking, isSpeaking ? currentPlayingServiceKey : null);
  return () => {
    listeners.delete(listener);
  };
}

export function isServiceVoicePlaying(serviceKey?: string): boolean {
  const isSpeaking = Boolean(
    currentPlayingServiceKey !== null ||
    currentAudioBufferSource !== null ||
    (typeof window !== 'undefined' && 'speechSynthesis' in window && window.speechSynthesis.speaking) ||
    (currentAudioPlayer && !currentAudioPlayer.paused && Boolean(currentAudioPlayer.src) && currentAudioPlayer.src !== SILENT_WAV_DATA_URI)
  );
  if (!isSpeaking) return false;
  if (!serviceKey) return true;
  const resolved = resolveServiceKey(serviceKey);
  if (!resolved) return false;
  return resolved === currentPlayingServiceKey;
}

/**
 * 1 & 2. Voice resolution with instant fallback:
 * Requested language -> Hindi ('hi-IN') -> Indian English ('en-IN') -> Default voice
 */
function resolveVoiceAndLanguage(langCode: VoiceLanguageCode): { voice: SpeechSynthesisVoice | null; lang: string } {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
    return { voice: null, lang: 'hi-IN' };
  }

  const voices = window.speechSynthesis.getVoices() || [];
  const requestedTag = VOICE_LANGUAGE_TAGS[langCode] || 'hi-IN';

  if (voices.length > 0) {
    const exactVoice = voices.find((v) => v.lang.replace('_', '-').toLowerCase() === requestedTag.toLowerCase());
    if (exactVoice) return { voice: exactVoice, lang: exactVoice.lang };

    const prefixVoice = voices.find((v) => v.lang.replace('_', '-').toLowerCase().startsWith(langCode.toLowerCase()));
    if (prefixVoice) return { voice: prefixVoice, lang: prefixVoice.lang };

    const hindiVoice = voices.find((v) => {
      const vLang = v.lang.replace('_', '-').toLowerCase();
      return vLang === 'hi-in' || vLang.startsWith('hi');
    });
    if (hindiVoice) return { voice: hindiVoice, lang: 'hi-IN' };

    const englishVoice = voices.find((v) => {
      const vLang = v.lang.replace('_', '-').toLowerCase();
      return vLang === 'en-in' || vLang.startsWith('en');
    });
    if (englishVoice) return { voice: englishVoice, lang: 'en-IN' };

    const defaultVoice = voices.find((v) => v.default) || voices[0];
    if (defaultVoice) return { voice: defaultVoice, lang: defaultVoice.lang || requestedTag };
  }

  return { voice: null, lang: requestedTag };
}

