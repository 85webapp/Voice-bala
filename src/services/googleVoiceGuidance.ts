// Active play session tracking to ensure ONLY ONE voice can ever play at any instant
let currentPlaySessionId = 0;

function cleanupAudioElementHandlers(audio: HTMLAudioElement | null) {
  if (!audio) return;
  audio.onloadedmetadata = null;
  audio.onplay = null;
  audio.onended = null;
  audio.onerror = null;
}

/**
 * 4. MUTE / STOP CONTROLS:
 * Stops any playing speech, Web Audio buffer, or HTMLAudioElement immediately without stale error callbacks
 */
export function stopServiceVoice() {
  currentPlaySessionId++;

  if (speechHeartbeatTimer) {
    clearInterval(speechHeartbeatTimer);
    speechHeartbeatTimer = null;
  }

  if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
    try {
      if (window.speechSynthesis.speaking || window.speechSynthesis.pending) {
        window.speechSynthesis.cancel();
      }
    } catch {}
  }

  if (currentAudioBufferSource) {
    try {
      currentAudioBufferSource.onended = null;
      currentAudioBufferSource.stop();
      currentAudioBufferSource.disconnect();
    } catch {}
    currentAudioBufferSource = null;
  }

  if (currentAudioPlayer) {
    cleanupAudioElementHandlers(currentAudioPlayer);
    try {
      currentAudioPlayer.pause();
      currentAudioPlayer.currentTime = 0;
    } catch {}
    currentAudioPlayer = null;
  }

  if (currentBlobUrl) {
    try {
      URL.revokeObjectURL(currentBlobUrl);
    } catch {}
    currentBlobUrl = null;
  }

  currentUtterance = null;
  currentPlayingServiceKey = null;
  notifyListeners();
}

async function playChunkWithWebAudioFallback(
  audioBuffer: ArrayBuffer,
  textToSpeak: string,
  userLang: VoiceLanguageCode,
  canonicalKey: string,
  thisSession: number,
  onChunkComplete: () => void
) {
  if (thisSession !== currentPlaySessionId) return;

  if (!sharedAudioContext) {
    const AudioCtx = window.AudioContext || (window as any).webkitAudioContext;
    if (AudioCtx) {
      sharedAudioContext = new AudioCtx();
    }
  }

  if (!sharedAudioContext) {
    fallbackToSpeechSynthesis(textToSpeak, userLang, canonicalKey, thisSession);
    return;
  }

  try {
    if (sharedAudioContext.state === 'suspended') {
      await sharedAudioContext.resume();
    }
    if (thisSession !== currentPlaySessionId) return;

    const decoded = await sharedAudioContext.decodeAudioData(audioBuffer.slice(0));
    if (thisSession !== currentPlaySessionId) return;

    const source = sharedAudioContext.createBufferSource();
    source.buffer = decoded;
    source.playbackRate.value = 1.3;
    source.connect(sharedAudioContext.destination);

    source.onended = () => {
      if (currentAudioBufferSource === source) {
        currentAudioBufferSource = null;
      }
      if (thisSession === currentPlaySessionId) {
        onChunkComplete();
      }
    };

    currentAudioBufferSource = source;
    currentPlayingServiceKey = canonicalKey;
    source.start(0);
    notifyListeners();
  } catch (err) {
    if (thisSession !== currentPlaySessionId) return;
    console.warn('[VoiceGuidance] Web Audio fallback failed, using SpeechSynthesis:', err);
    fallbackToSpeechSynthesis(textToSpeak, userLang, canonicalKey, thisSession);
  }
}

function playChunkWithHtmlAudioFirst(
  audioBuffer: ArrayBuffer,
  textToSpeak: string,
  userLang: VoiceLanguageCode,
  canonicalKey: string,
  thisSession: number,
  onChunkComplete: () => void
) {
  if (thisSession !== currentPlaySessionId) return;

  const blob = new Blob([audioBuffer], { type: 'audio/mpeg' });
  const blobUrl = URL.createObjectURL(blob);
  if (thisSession !== currentPlaySessionId) {
    URL.revokeObjectURL(blobUrl);
    return;
  }

  if (currentBlobUrl) {
    try { URL.revokeObjectURL(currentBlobUrl); } catch {}
  }
  currentBlobUrl = blobUrl;

  const audio = sharedAudioElement || new Audio();
  sharedAudioElement = audio;
  currentAudioPlayer = audio;
  cleanupAudioElementHandlers(audio);

  audio.muted = false;
  audio.volume = 1.0;
  audio.src = blobUrl;
  audio.defaultPlaybackRate = 1.3;
  audio.playbackRate = 1.3;
  (audio as any).preservesPitch = true;

  audio.onloadedmetadata = () => {
    if (thisSession !== currentPlaySessionId) return;
    audio.playbackRate = 1.3;
  };

  audio.onplay = () => {
    if (thisSession !== currentPlaySessionId) {
      audio.pause();
      return;
    }
    audio.muted = false;
    audio.playbackRate = 1.3;
    currentPlayingServiceKey = canonicalKey;
    notifyListeners();
  };

  audio.onended = () => {
    if (thisSession !== currentPlaySessionId) return;
    onChunkComplete();
  };

  audio.onerror = () => {
    if (thisSession !== currentPlaySessionId) return;
    console.warn('[VoiceGuidance] HTML5 Blob audio failed, trying Web Audio API...');
    void playChunkWithWebAudioFallback(audioBuffer, textToSpeak, userLang, canonicalKey, thisSession, onChunkComplete);
  };

  const playPromise = audio.play();
  if (playPromise !== undefined) {
    playPromise
      .then(() => {
        if (thisSession !== currentPlaySessionId) {
          audio.pause();
          return;
        }
        audio.muted = false;
        audio.playbackRate = 1.3;
        currentPlayingServiceKey = canonicalKey;
        notifyListeners();
      })
      .catch((playErr) => {
        if (thisSession !== currentPlaySessionId) return;
        console.warn('[VoiceGuidance] HTMLAudio play interrupted/blocked, trying Web Audio API:', playErr);
        void playChunkWithWebAudioFallback(audioBuffer, textToSpeak, userLang, canonicalKey, thisSession, onChunkComplete);
      });
  }
}

function playChunkSequence(
  chunks: string[],
  chunkPromises: Promise<ArrayBuffer | null>[],
  index: number,
  userLang: VoiceLanguageCode,
  textToSpeak: string,
  canonicalKey: string,
  thisSession: number,
  preloadedBuffer?: ArrayBuffer
) {
  if (thisSession !== currentPlaySessionId) return;
  if (index >= chunks.length) {
    stopServiceVoice();
    return;
  }

  const advanceNext = () => {
    if (thisSession !== currentPlaySessionId) return;
    const nextIdx = index + 1;
    if (nextIdx >= chunks.length) {
      stopServiceVoice();
      return;
    }
    const nextCached = chunkAudioCache.get(getChunkCacheKey(userLang, chunks[nextIdx]));
    if (nextCached) {
      playChunkSequence(chunks, chunkPromises, nextIdx, userLang, textToSpeak, canonicalKey, thisSession, nextCached);
    } else {
      void chunkPromises[nextIdx].then((nextBuf) => {
        if (thisSession !== currentPlaySessionId) return;
        if (!nextBuf) {
          stopServiceVoice();
          return;
        }
        playChunkSequence(chunks, chunkPromises, nextIdx, userLang, textToSpeak, canonicalKey, thisSession, nextBuf);
      });
    }
  };

  if (preloadedBuffer) {
    playChunkWithHtmlAudioFirst(preloadedBuffer, textToSpeak, userLang, canonicalKey, thisSession, advanceNext);
    return;
  }

  void chunkPromises[index].then((buf) => {
    if (thisSession !== currentPlaySessionId) return;
    if (!buf) {
      if (index === 0) {
        fallbackToSpeechSynthesis(textToSpeak, userLang, canonicalKey, thisSession);
      } else {
        stopServiceVoice();
      }
      return;
    }
    playChunkWithHtmlAudioFirst(buf, textToSpeak, userLang, canonicalKey, thisSession, advanceNext);
  });
}

/**
 * Plays the voice guidance for the requested service immediately:
 * 1. Synchronously unlocks Web Audio API Context + HTMLAudioElement in the click gesture.
 * 2. Fires parallel chunk fetches for all sentence segments, or plays instantaneously (0ms)
 *    from chunkAudioCache if already prefetched / hovered.
 * 3. Plays Sentence 1 the instant it is ready while Sentences 2..N finish downloading in parallel.
 */
export function playServiceVoice(serviceKey: string) {
  stopServiceVoice();

  const resolved = getResolvedVoicePayload(serviceKey);
  if (!resolved) {
    return;
  }

  const { canonicalKey, userLang, textToSpeak, chunks } = resolved;
  const thisSession = ++currentPlaySessionId;

  // Synchronously mark active & unlock browser audio inside the click gesture
  currentPlayingServiceKey = canonicalKey;
  notifyListeners();
  unlockAudioForPlayback();

  // If /api/tts-audio is known unavailable (404/405), run SpeechSynthesis synchronously while user gesture is valid
  if (ttsBackendStatus === 'unavailable') {
    fallbackToSpeechSynthesis(textToSpeak, userLang, canonicalKey, thisSession);
    return;
  }

  // Launch parallel fetches for ALL sentence chunks immediately (deduped against any prefetch)
  const chunkPromises = chunks.map((chunk) => fetchSingleTtsChunk(chunk, userLang));
  const cachedFirst = chunkAudioCache.get(getChunkCacheKey(userLang, chunks[0]));

  playChunkSequence(chunks, chunkPromises, 0, userLang, textToSpeak, canonicalKey, thisSession, cachedFirst);
}

function splitSpeechChunks(text: string, maxLength = 160): string[] {
  if (text.length <= maxLength) return [text];
  const sentences = text.split(/(?<=[।!?.\n])\s+/);
  const chunks: string[] = [];
  let cur = '';
  for (const s of sentences) {
    if (!s.trim()) continue;
    if ((cur + ' ' + s).trim().length <= maxLength) {
      cur = cur ? `${cur} ${s}` : s;
    } else {
      if (cur.trim()) chunks.push(cur.trim());
      cur = s.trim();
    }
  }
  if (cur.trim()) chunks.push(cur.trim());
  return chunks.length > 0 ? chunks : [text];
}

/**
 * Fallback to browser SpeechSynthesis when /api/tts-audio or HTMLAudioElement is unavailable
 */
function fallbackToSpeechSynthesis(textToSpeak: string, userLang: VoiceLanguageCode, canonicalKey: string, thisSession: number) {
  if (typeof window === 'undefined' || !('speechSynthesis' in window) || typeof SpeechSynthesisUtterance === 'undefined') {
    if (thisSession === currentPlaySessionId) {
      stopServiceVoice();
    }
    return;
  }

  try {
    if (window.speechSynthesis.paused) {
      window.speechSynthesis.resume();
    }
    if (window.speechSynthesis.speaking || window.speechSynthesis.pending) {
      window.speechSynthesis.cancel();
    }

    const { voice, lang } = resolveVoiceAndLanguage(userLang);
    const chunks = splitSpeechChunks(textToSpeak, 160);
    let chunkIndex = 0;

    if (speechHeartbeatTimer) {
      clearInterval(speechHeartbeatTimer);
    }
    speechHeartbeatTimer = setInterval(() => {
      if (thisSession === currentPlaySessionId && window.speechSynthesis.speaking) {
        try {
          window.speechSynthesis.pause();
          window.speechSynthesis.resume();
        } catch {}
      }
    }, 8000);

    const speakNextChunk = () => {
      if (thisSession !== currentPlaySessionId) return;
      if (chunkIndex >= chunks.length) {
        stopServiceVoice();
        return;
      }

      const utterance = new SpeechSynthesisUtterance(chunks[chunkIndex]);
      currentUtterance = utterance;
      (window as any).currentUtterance = utterance;

      utterance.lang = lang;
      utterance.rate = 1.3;
      utterance.pitch = 1.0;
      utterance.volume = 1.0;
      if (voice) utterance.voice = voice;

      utterance.onstart = () => {
        if (thisSession !== currentPlaySessionId) {
          try { window.speechSynthesis.cancel(); } catch {}
          return;
        }
        currentPlayingServiceKey = canonicalKey;
        notifyListeners();
      };

      utterance.onend = () => {
        if (thisSession !== currentPlaySessionId) return;
        chunkIndex++;
        speakNextChunk();
      };

      utterance.onerror = (e) => {
        if (thisSession !== currentPlaySessionId) return;
        if (e.error === 'interrupted' || e.error === 'canceled') {
          currentPlayingServiceKey = null;
          notifyListeners();
          return;
        }
        stopServiceVoice();
      };

      window.speechSynthesis.speak(utterance);
      currentPlayingServiceKey = canonicalKey;
      notifyListeners();
    };

    speakNextChunk();
  } catch {
    if (thisSession === currentPlaySessionId) {
      stopServiceVoice();
    }
  }
}

/**
 * Toggle voice playback for a service
 */
export function toggleServiceVoice(serviceKey: string) {
  const canonicalKey = resolveServiceKey(serviceKey);
  if (!canonicalKey) {
    stopServiceVoice();
    return;
  }
  if (isServiceVoicePlaying(canonicalKey)) {
    stopServiceVoice();
  } else {
    playServiceVoice(canonicalKey);
  }
}

